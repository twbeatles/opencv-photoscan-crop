from __future__ import annotations

from typing import Any, Optional, Protocol

from .sqlite_store import LibrarySqliteStore


class LibraryRepositoryProtocol(Protocol):
    store: LibrarySqliteStore

    @property
    def fts_enabled(self) -> bool: ...

    def refresh_search_index(self, asset_id: int) -> None: ...
    def _invalid_source_record(self, source_path: str, error: str) -> dict[str, Any]: ...
    def _asset_search_fields(self, conn: Any, asset_id: int) -> dict[str, str]: ...
    def _build_asset_query_sql(self, *args: Any, **kwargs: Any) -> tuple[str, list[Any]]: ...
    def search_asset_ids(self, text: str) -> list[int]: ...
    def get_asset_detail(self, asset_id: int) -> Optional[dict[str, Any]]: ...
    def mark_search_index_dirty(self) -> None: ...
    def clear_search_index_dirty(self) -> None: ...
    def get_search_index_dirty(self) -> bool: ...
    def rebuild_search_index(self) -> int: ...

    def _refresh_asset_primary_source(self, conn: Any, asset_id: int) -> None: ...
    def _source_candidates_by_hash(
        self,
        conn: Any,
        source_hash: str,
        *,
        missing_only: bool = False,
    ) -> list[dict[str, Any]]: ...

    def list_collections_for_asset(self, asset_id: int) -> list[dict[str, Any]]: ...
    def list_tags_for_asset(self, asset_id: int) -> list[dict[str, Any]]: ...
    def list_ocr_documents(self, asset_id: int) -> list[dict[str, Any]]: ...
    def list_faces_for_asset(self, asset_id: int) -> list[dict[str, Any]]: ...
    def list_people_for_asset(self, asset_id: int) -> list[dict[str, Any]]: ...
    def list_review_items_for_asset(self, asset_id: int) -> list[dict[str, Any]]: ...
    def list_review_items(self, *, limit: int = 500) -> list[dict[str, Any]]: ...
    def list_job_items_for_asset(self, asset_id: int) -> list[dict[str, Any]]: ...
    def list_assets(self, *args: Any, **kwargs: Any) -> list[dict[str, Any]]: ...
    def count_assets(self, *args: Any, **kwargs: Any) -> int: ...
    def get_asset_visual_path(self, asset_id: int) -> str: ...
    def set_asset_perceptual_hash(self, asset_id: int, value: str) -> None: ...
    def get_duplicate_member_preferences(self, kind: str) -> dict[int, dict[str, Any]]: ...
    def ensure_tag(self, name: str, *, kind: str = "user") -> Optional[int]: ...
    def list_duplicate_groups(self, *, kind: Optional[str] = None) -> list[dict[str, Any]]: ...
    def list_duplicate_group_members(self, group_id: int) -> list[dict[str, Any]]: ...
    def set_duplicate_member_preference(
        self,
        kind: str,
        asset_id: int,
        *,
        excluded: Optional[bool] = None,
        prefer_representative: Optional[bool] = None,
    ) -> None: ...
